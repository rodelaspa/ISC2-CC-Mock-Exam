export function getTranslation(key: string, lang: LanguageCode = 'en', params?: Record<string, string | number>): string {
  if (key === 'flashcards.cardOf' && !params) {
    return SUPPLEMENTAL_TRANSLATIONS[lang]?.['flashcards.cardWord'] || 'Card';
  }
  const resolvedKey = KEY_ALIASES[key] || key;
  const hasParams = !!params && Object.keys(params).length > 0;

  let text = hasParams
    ? EXTRA_TRANSLATIONS[lang]?.[resolvedKey] ||
      TRANSLATIONS[lang]?.[resolvedKey] ||
      SUPPLEMENTAL_TRANSLATIONS[lang]?.[resolvedKey] ||
      EXTRA_TRANSLATIONS['en']?.[resolvedKey] ||
      TRANSLATIONS['en']?.[resolvedKey] ||
      SUPPLEMENTAL_TRANSLATIONS['en']?.[resolvedKey] ||
      key
    : SUPPLEMENTAL_TRANSLATIONS[lang]?.[resolvedKey] ||
      EXTRA_TRANSLATIONS[lang]?.[resolvedKey] ||
      TRANSLATIONS[lang]?.[resolvedKey] ||
      SUPPLEMENTAL_TRANSLATIONS['en']?.[resolvedKey] ||
      EXTRA_TRANSLATIONS['en']?.[resolvedKey] ||
      TRANSLATIONS['en']?.[resolvedKey] ||
      key;

  if (resolvedKey === 'flashcards.examTipLabel' || resolvedKey === 'history.domainAccuracy') {
    text = text.replace(/[:：]\s*$/, '');
  }
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  // Defensive cleanup so raw {placeholder} tokens never leak to the UI
  if (text.includes('{')) {
    text = text
      .replace(/\{score\}/g, '70')
      .replace(/\(\s*\{[a-zA-Z0-9_]+\}\s*\)/g, '')
      .replace(/\{[a-zA-Z0-9_]+\}/g, '')
      .replace(/\s{2,}/g, ' ')
      .trim();
  }
  return text;
}

export function getDomainTranslation(domainId: 1 | 2 | 3 | 4 | 5, lang: LanguageCode = 'en'): string {
  return getTranslation(`domain.${domainId}`, lang);
}

export function loadSavedLanguage(): LanguageCode {
  try {
    const saved = localStorage.getItem('isc2_cc_language') as LanguageCode;
    if (saved && TRANSLATIONS[saved]) return saved;
    // Auto-detect browser language
    const browserLang = navigator.language.slice(0, 2).toLowerCase() as LanguageCode;
    if (browserLang && TRANSLATIONS[browserLang]) return browserLang;
    return 'en';
  } catch {
    return 'en';
  }
}

export function saveLanguage(code: LanguageCode): void {
  try {
    localStorage.setItem('isc2_cc_language', code);
  } catch {
    // Ignore storage errors
  }
}

interface I18nContextType {
  language: LanguageCode;
  setLanguage: (lang: LanguageCode) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
  dir: 'ltr' | 'rtl';
  tDomain: (domainId: 1 | 2 | 3 | 4 | 5) => string;
}

const I18nContext = createContext<I18nContextType>({
  language: 'en',
  setLanguage: () => {},
  t: (k, params) => getTranslation(k, 'en', params),
  dir: 'ltr',
  tDomain: (id) => getDomainTranslation(id, 'en'),
});

export const I18nProvider: React.FC<{
  children: React.ReactNode;
  initialLanguage?: LanguageCode;
  onLanguageChange?: (lang: LanguageCode) => void;
}> = ({ children, initialLanguage, onLanguageChange }) => {
  const [language, setLanguageState] = useState<LanguageCode>(() => initialLanguage || loadSavedLanguage());

  useEffect(() => {
    if (initialLanguage && initialLanguage !== language) {
      setLanguageState(initialLanguage);
    }
  }, [initialLanguage, language]);

  const setLanguage = (newLang: LanguageCode) => {
    setLanguageState(newLang);
    saveLanguage(newLang);
    if (onLanguageChange) {
      onLanguageChange(newLang);
    }
  };

  useEffect(() => {
    document.documentElement.lang = language;
    // Maintain steady LTR layout structure so cards, columns, and navigation do not reverse horizontally
    document.documentElement.dir = 'ltr';
  }, [language]);

  const dir: 'ltr' | 'rtl' = 'ltr';

  const t = useMemo(() => {
    return (key: string, params?: Record<string, string | number>) => getTranslation(key, language, params);
  }, [language]);

  const tDomain = useMemo(() => {
    return (domainId: 1 | 2 | 3 | 4 | 5) => getDomainTranslation(domainId, language);
  }, [language]);

  const value = useMemo(
    () => ({
      language,
      setLanguage,
      t,
      dir,
      tDomain,
    }),
    [language, t, dir, tDomain]
  );

  return React.createElement(I18nContext.Provider, { value }, children);
};

export const useI18n = () => useContext(I18nContext);
